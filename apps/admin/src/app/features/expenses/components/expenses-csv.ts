/** What a report covers and who made it: the block at the top of every export. */
export interface ExpenseReportMeta {
  readonly arena: string;
  readonly period: ExpensePeriod;
  readonly generatedAt: Date;
  /** "Name <email>" of the signed-in login. */
  readonly generatedBy: string | null;
  /** The list's filters, when any. */
  readonly filters: string | null;
}

const TIME_ZONE = 'Asia/Kolkata (IST, UTC+05:30)';

/** Paise as rupees with two decimals (no symbol, no grouping), a number to spreadsheets. */
function money(paise: number): string {
  return (paise / 100).toFixed(2);
}

function row(cells: readonly string[]): string {
  return cells.join(',');
}

function header(meta: ExpenseReportMeta, title: string, basis: string): string[] {
  const p = meta.period;
  const days = p.first === p.last ? p.first : `${p.first} to ${p.last}`;
  const at = meta.generatedAt;
  return [
    row([textCell(`${meta.arena} — ${title}`)]),
    row(['Arena', textCell(meta.arena)]),
    row(['Period', textCell(`${days} (IST calendar days; ${basis})`)]),
    row(['Time zone', textCell(TIME_ZONE)]),
    row(['Generated', textCell(`${formatIsoDate(at)} ${formatHm(at)} IST (${at.toISOString()})`)]),
    row(['Generated by', textCell(meta.generatedBy ?? '')]),
    ...(meta.filters ? [row(['Filters', textCell(meta.filters)])] : []),
    row([
      'Note',
      textCell(
        'Paid from: Company = the arena’s own account; Personal = an owner’s own money (their contribution, not company cash out).',
      ),
    ]),
    '',
  ];
}

const EXPENSE_HEAD = [
  'Date',
  'Period start',
  'Period end',
  'Title',
  'Kind',
  'Category',
  'Staff',
  'Amount (INR)',
  'Paid from company (INR)',
  'Paid personally (INR)',
  'Paid (INR)',
  'Balance (INR)',
  'Status',
  'Void reason',
  'Notes',
  'Added by',
  'Added at (UTC)',
  'Expense ID',
];

/**
 * Expenses report: one row per expense dated in the period (a salary: its period's last day),
 * voided ones included and marked, then the totals of the active ones.
 */
export function expensesCsv(expenses: readonly Expense[], meta: ExpenseReportMeta): string {
  const lines = header(
    meta,
    'Expenses',
    'an expense belongs to its date; a salary to its last day',
  );
  lines.push(row(EXPENSE_HEAD.map(textCell)));
  for (const e of expenses) {
    lines.push(
      row([
        e.expenseDate,
        e.periodStart ?? '',
        e.periodEnd ?? '',
        textCell(e.title),
        e.kind === 'salary' ? 'Salary' : 'Expense',
        textCell(e.categoryName),
        textCell(e.staffName),
        money(e.amountPaise),
        money(e.paidCompanyPaise),
        money(e.paidPersonalPaise),
        money(e.paidPaise),
        money(e.balancePaise),
        expenseState(e).label,
        textCell(e.voidReason),
        textCell(e.notes),
        textCell(e.createdByName),
        e.createdAt,
        e.id,
      ]),
    );
  }
  const t = expenseTotals(expenses);
  lines.push(
    '',
    row(['Totals (voided expenses excluded)']),
    row(['Expenses', String(t.count)]),
    row(['Incurred (INR)', money(t.incurredPaise)]),
    row(['Paid from company (INR)', money(t.paidCompanyPaise)]),
    row(['Paid personally (INR)', money(t.paidPersonalPaise)]),
    row(['Unpaid (INR)', money(t.unpaidPaise)]),
    row(['Voided', String(t.voidedCount)]),
  );
  return lines.join('\n') + '\n';
}

const PAYMENT_HEAD = [
  'Paid on',
  'Kind',
  'Amount (INR)',
  'Method',
  'Paid from',
  'Payer',
  'Expense',
  'Expense kind',
  'Category',
  'Staff',
  'Expense voided',
  'Reverses payment ID',
  'Note',
  'Payment ID',
  'Expense ID',
];

/**
 * Payments ledger: every payment and reversal made in the period (by the day the money went
 * out), with whose money it was, then company and personal totals and each owner's net.
 */
export function expensePaymentsCsv(
  payments: readonly PaymentLine[],
  meta: ExpenseReportMeta,
): string {
  const lines = header(meta, 'Expense payments', 'a payment belongs to the day it was paid');
  lines.push(row(PAYMENT_HEAD.map(textCell)));
  for (const p of payments) {
    lines.push(
      row([
        p.paidOn,
        p.kind === 'reversal' ? 'Reversal' : 'Payment',
        money(p.amountPaise),
        expenseMethodName(p.method),
        p.paidFrom === 'company' ? 'Company' : 'Personal',
        textCell(p.payerName),
        textCell(p.expenseTitle),
        p.expenseKind === 'salary' ? 'Salary' : 'Expense',
        textCell(p.categoryName),
        textCell(p.staffName),
        p.expenseVoided ? 'Yes' : 'No',
        p.reversesId ?? '',
        textCell(p.note),
        p.id,
        p.expenseId,
      ]),
    );
  }
  const c = cashTotals(payments);
  lines.push(
    '',
    row(['Totals (payments minus reversals)']),
    row(['From company account (INR)', money(c.companyPaise)]),
    row(['Paid personally by owners (INR)', money(c.personalPaise)]),
    row(['Salaries paid (INR)', money(c.salariesPaise)]),
    ...c.owners.map((o) => row([textCell(`Personal · ${o.name}`), money(o.netPaise)])),
  );
  return lines.join('\n') + '\n';
}

/**
 * Saves `csv` as `filename` (a byte-order mark first, so spreadsheet apps read ₹ and names as
 * UTF-8). A blocked download (a sandboxed preview) fails quietly: the snackbar still reports.
 */
export function downloadCsv(document: Document, csv: string, filename: string): void {
  try {
    const url = URL.createObjectURL(new Blob(['﻿', csv], { type: 'text/csv' }));
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    setTimeout(() => URL.revokeObjectURL(url));
  } catch {
    // Download blocked.
  }
}

/** "404-arena-expenses-2026-10-01_to_2026-10-31.csv". */
export function csvName(arena: string, what: string, period: ExpensePeriod): string {
  const slug = arena.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  const days = period.first === period.last ? period.first : `${period.first}_to_${period.last}`;
  return `${slug || 'arena'}-${what}-${days}.csv`;
}
